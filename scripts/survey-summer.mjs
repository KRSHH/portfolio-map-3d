// Generates src/summer/mapSurvey.ts: baked obstacle circles + a coarse terrain height
// grid from the decoded SummerTime geometry, so the map overlay plan (mapPlan.ts)
// can place pins and structures on open, dry ground without a WebGL context.
// Usage: node scripts/survey-summer.mjs   (needs devDependency draco3d)
import fs from "node:fs";
import { execSync } from "node:child_process";

const JSON_PATH = "C:/Users/Krish/AppData/Local/Temp/opencode/summer-geo.json";
if (!fs.existsSync(JSON_PATH)) {
  console.log("decoding geometries first…");
  execSync("node scripts/analyze-summer.mjs --json", { stdio: "inherit" });
}
const d = JSON.parse(fs.readFileSync(JSON_PATH, "utf8"));
const inst = (f) => d[f].instances;

// Hub elements the overlay itself adds (monument, portal, pylons, spawn).
const HUB = { monument: [12, 2], portal: [-2, 3], spawn: [12, -9.5] };
const PYLONS = [38, 72, 108, 142].map((deg) => {
  const a = (deg * Math.PI) / 180;
  return [+(HUB.monument[0] + 9.5 * Math.cos(a)).toFixed(2), +(HUB.monument[1] + 9.5 * Math.sin(a)).toFixed(2)];
});
// District cluster centers (locked after clearance analysis, Oct 2026).
const CLUSTERS = {
  health: [16, 60], people: [-6, 62], "ai-data": [28, 42], hardware: [-32, 16],
  climate: [26, -42], fintech: [-16, -58], commerce: [24, -64],
};
const KEEP = [...Object.values(CLUSTERS), HUB.monument, HUB.portal, HUB.spawn, ...PYLONS];

const hard = [];
const nearKeep = (x, z, r) => KEEP.some(([kx, kz]) => Math.hypot(x - kx, z - kz) < r + 20);
for (const [file, kind, r] of [
  ["tree-instances.bin", "tree", 2.2],
  ["rock1-instances.bin", "rock", 1.3],
  ["rock2-instances.bin", "rock", 1.0],
  ["lightposts-instances.bin", "lamp", 0.8],
  ["palmtree-instances.bin", "palm", 1.6],
]) {
  for (const p of inst(file)) {
    if (nearKeep(p[0], p[2], r)) hard.push({ k: kind, x: +p[0].toFixed(2), z: +p[2].toFixed(2), r });
  }
}
// Buildings, machines, set pieces and street blockers always matter.
hard.push(
  { k: "house", x: 31.2, z: 7.7, r: 7.5 }, { k: "house", x: -5.6, z: -11.5, r: 8.5 }, { k: "house", x: 31.4, z: -7.1, r: 7.5 },
  { k: "house", x: 40.5, z: 10.1, r: 4.5 }, { k: "house", x: -5, z: -28.5, r: 3.5 }, { k: "house", x: -54.9, z: -46.9, r: 4.5 },
  { k: "machine", x: 57.1, z: -29.9, r: 2.5 }, { k: "machine", x: 0, z: 45.1, r: 2.5 }, { k: "machine", x: 0.3, z: -56.5, r: 2.5 },
  { k: "cats", x: 27.5, z: -4.1, r: 1.5 }, { k: "sloth", x: -8.4, z: 46.2, r: 1.5 }, { k: "ufo", x: -56.9, z: 22.7, r: 4.5 },
  { k: "gossip", x: -55.9, z: -47.3, r: 1.5 }, { k: "alien", x: 60.1, z: 40.6, r: 1.5 },
  { k: "blocker", x: 11.9, z: -83.5, r: 8 }, { k: "blocker", x: 15.4, z: 83.8, r: 6 },
);
hard.sort((a, b) => a.x - b.x || a.z - b.z);

// Coarse height grid (10u) for dry-ground checks and Y fallbacks.
const grid = {};
for (let gz = -70; gz <= 70; gz += 10) {
  for (let gx = -70; gx <= 70; gx += 10) {
    let best = 1e12, by = 0;
    for (const key of Object.keys(d["terrain.bin"].heightGrid)) {
      const [hx, hz] = key.split(",").map(Number);
      const dd = (hx - gx) ** 2 + (hz - gz) ** 2;
      if (dd < best) { best = dd; by = d["terrain.bin"].heightGrid[key]; }
    }
    grid[`${gx},${gz}`] = by;
  }
}

const out = `/* GENERATED by scripts/survey-summer.mjs from public/summer/geometries — do not edit by hand.
   Obstacle circles near the overlay's hub and district clusters (x/z in town units),
   plus a coarse terrain height grid for dry-ground checks and Y fallbacks. */
export interface Obstacle { k: string; x: number; z: number; r: number }
export const OBSTACLES: Obstacle[] = ${JSON.stringify(hard)};
export const HUB_SPOTS = {
  monument: [${HUB.monument}] as [number, number],
  portal: [${HUB.portal}] as [number, number],
  spawn: [${HUB.spawn}] as [number, number],
  pylons: ${JSON.stringify(PYLONS)} as [number, number][],
};
export const CLUSTER_SPOTS: Record<string, [number, number]> = ${JSON.stringify(CLUSTERS, null, 2)};
export const HEIGHT_GRID: Record<string, number> = ${JSON.stringify(grid)};
`;
fs.writeFileSync("src/summer/mapSurvey.ts", out);
console.log(`wrote src/summer/mapSurvey.ts (${hard.length} obstacles, ${Object.keys(grid).length} heights)`);
